export type Dictionary = typeof en;
export type Language = "zh" | "en";

const verdictLabels: Record<string, string> = {
  PENDING: "Pending",
  JUDGING: "Judging",
  ACCEPTED: "Accepted",
  WRONG_ANSWER: "Wrong Answer",
  TIME_LIMIT_EXCEEDED: "Time Limit Exceeded",
  MEMORY_LIMIT_EXCEEDED: "Memory Limit Exceeded",
  RUNTIME_ERROR: "Runtime Error",
  COMPILE_ERROR: "Compile Error",
  PRESENTATION_ERROR: "Presentation Error",
  SYSTEM_ERROR: "System Error",
  FROZEN: "Frozen",
  REJECTED: "Rejected",
};

const verdictsWithFailedTest = new Set([
  "WRONG_ANSWER",
  "TIME_LIMIT_EXCEEDED",
  "MEMORY_LIMIT_EXCEEDED",
  "PRESENTATION_ERROR",
  "RUNTIME_ERROR",
]);

export function getVerdictLabel(verdict: string, testNumber?: number) {
  const label = Object.hasOwn(verdictLabels, verdict) ? verdictLabels[verdict] : verdict;
  if (testNumber === undefined) return label;
  if (verdict === "JUDGING") return `Running on test ${testNumber}…`;
  return verdictsWithFailedTest.has(verdict) ? `${label} on test ${testNumber}` : label;
}

export function getLocale(lang: Language) {
  return lang === "zh" ? "zh-CN" : "en-US";
}

export function formatMessage(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (placeholder, key) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  );
}
